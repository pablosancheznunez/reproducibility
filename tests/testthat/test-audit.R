new_dir <- function() {
  d <- tempfile("proj")
  dir.create(d)
  d
}
status <- function(a, id) a$checks$status[a$checks$id == id]

test_that("an empty directory fails the critical items and skips code checks", {
  a <- rr_audit(new_dir())
  expect_s3_class(a, "rr_audit")
  expect_equal(status(a, "readme"), "not_met")
  expect_equal(status(a, "license"), "not_met")
  expect_equal(status(a, "no_absolute_paths"), "not_applicable")
  expect_equal(status(a, "data_documented"), "not_applicable")
  expect_true(all(a$checks$status %in% c("met", "not_met", "not_applicable", "unverifiable")))
  expect_equal(nrow(a$checks), nrow(rr_checklist()))
})

test_that("the template meets most items but leaves the licence to the authors", {
  d <- new_dir()
  created <- rr_template(d, title = "Study")
  expect_true(all(file.exists(created)))
  a <- rr_audit(d)
  expect_equal(status(a, "readme"), "met")
  expect_equal(status(a, "citation"), "met")
  expect_equal(status(a, "pipeline"), "met")
  expect_equal(status(a, "license"), "not_met")
  expect_equal(status(a, "no_absolute_paths"), "met")
  writeLines("changed", file.path(d, "README.md"))
  rr_template(d)
  expect_equal(readLines(file.path(d, "README.md")), "changed")
})

test_that("absolute paths, missing seeds and pinned dependencies are detected with evidence", {
  d <- new_dir()
  writeLines(c("x <- 1", "setwd(\"C:/Users/me/study\")", "y <- rnorm(10)"), file.path(d, "analysis.R"))
  writeLines(c("pandas==2.2.0", "numpy==1.26.4"), file.path(d, "requirements.txt"))
  a <- rr_audit(d)
  expect_equal(status(a, "no_absolute_paths"), "not_met")
  expect_match(a$checks$evidence[a$checks$id == "no_absolute_paths"], "analysis.R:2")
  expect_equal(status(a, "seeds_set"), "not_met")
  expect_equal(status(a, "dependencies_pinned"), "met")
  writeLines(c("set.seed(1)", "y <- rnorm(10)"), file.path(d, "analysis.R"))
  writeLines(c("pandas>=2", "numpy"), file.path(d, "requirements.txt"))
  a <- rr_audit(d)
  expect_equal(status(a, "seeds_set"), "met")
  expect_equal(status(a, "no_absolute_paths"), "met")
  expect_equal(status(a, "dependencies_declared"), "met")
  expect_equal(status(a, "dependencies_pinned"), "not_met")
})

test_that("data referenced by DOI in the README count as available", {
  d <- new_dir()
  writeLines("Data: https://doi.org/10.5281/zenodo.123", file.path(d, "README.md"))
  a <- rr_audit(d)
  expect_equal(status(a, "data_available"), "met")
  expect_equal(status(a, "data_documented"), "not_met")
})

test_that("large files and CI are detected; renv libraries are ignored", {
  d <- new_dir()
  dir.create(file.path(d, "renv/library/x"), recursive = TRUE)
  writeLines("setwd(\"/home/me\")", file.path(d, "renv/library/x/bad.R"))
  writeLines(strrep("x", 2e5), file.path(d, "big.csv"))
  rr_use_github_action(d)
  a <- rr_audit(d, large_file_mb = 0.1)
  expect_equal(status(a, "no_large_files"), "not_met")
  expect_equal(status(a, "ci"), "met")
  expect_equal(status(a, "no_absolute_paths"), "not_applicable")
  expect_message(rr_use_github_action(d), "not overwritten")
})

test_that("R packages are recognised and not asked for a pipeline or research data", {
  d <- new_dir()
  writeLines(c("Package: demo", "License: MIT + file LICENSE"), file.path(d, "DESCRIPTION"))
  dir.create(file.path(d, "inst/extdata"), recursive = TRUE)
  writeLines("{}", file.path(d, "inst/extdata/catalogue.json"))
  a <- rr_audit(d)
  expect_equal(a$project_type, "r-package")
  expect_equal(status(a, "pipeline"), "not_applicable")
  expect_equal(status(a, "data_available"), "not_applicable")
  expect_equal(status(a, "data_documented"), "not_applicable")
  expect_equal(status(a, "license"), "met")
  expect_equal(rr_audit(new_dir())$project_type, "research-project")
})

test_that("audits print, report and serialise", {
  d <- new_dir()
  rr_template(d)
  a <- rr_audit(d)
  expect_output(print(a), "not a reproduction")
  html <- paste(readLines(rr_report(a, tempfile(fileext = ".html"))), collapse = "")
  expect_match(html, "does not run the analysis")
  expect_match(html, "FAIR4RS")
  j <- jsonlite::read_json(rr_write_json(a, tempfile(fileext = ".json")))
  expect_equal(j$schema, "rr-audit/1")
  expect_length(j$checks, nrow(rr_checklist()))
  expect_error(rr_audit("no/such/dir"), "existing directory")
  expect_error(rr_report(list(), tempfile()), "rr_audit")
})
